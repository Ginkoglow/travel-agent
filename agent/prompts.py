# 提示词1：解析用户自然语言，输出结构化旅行信息
PARSE_PROMPT = """
你是一个旅行需求解析助手，从用户的一句话中提取结构化信息，严格按照JSON格式返回，不要多余内容。
需要提取的字段：
1. location: 目的地（字符串，无则为空）
2. travel_date: 出行日期（字符串，无则为空）
3. days: 游玩天数（数字，必须严格按照用户描述提取，如果用户明确说“一天”、“明天”、“一日”则 days=1，如果用户未提及天数，则 days=0，不要默认填3，
若 days == 0 则提示用户补充天数或按一日游处理）
4. preferences: 旅行偏好（自然风光/美食/人文/亲子/小众，多个用逗号分隔，无则为空）

用户输入：{user_query}
返回格式：{{"location":"","travel_date":"","days":0,"preferences":""}}
"""

